def downscale_2x(src_pixels, w, h):
    out_w = w // 2
    out_h = h // 2
    out = bytearray(out_w * out_h * 3)
    stride = w * 3
    paper_pixel = bytes(COLOR_PAPER)
    paper_row_src = paper_pixel * w
    paper_row_out = paper_pixel * out_w

    idx_out = 0
    for y in range(0, h, 2):
        r0 = src_pixels[y * stride : (y + 1) * stride]
        r1 = src_pixels[(y + 1) * stride : (y + 2) * stride]
        if r0 == paper_row_src and r1 == paper_row_src:
            out[idx_out : idx_out + out_w * 3] = paper_row_out
            idx_out += out_w * 3
            continue
        for x in range(0, stride, 6):
            out[idx_out]     = (r0[x]   + r0[x+3] + r1[x]   + r1[x+3] + 2) >> 2
            out[idx_out + 1] = (r0[x+1] + r0[x+4] + r1[x+1] + r1[x+4] + 2) >> 2
            out[idx_out + 2] = (r0[x+2] + r0[x+5] + r1[x+2] + r1[x+5] + 2) >> 2
            idx_out += 3
    return out

def write_png(filepath, img_bytes, w, h):
    raw = bytearray(h * (w * 3 + 1))
    stride = w * 3
    for y in range(h):
        offset = y * (stride + 1)
        raw[offset] = 0
        raw[offset + 1 : offset + 1 + stride] = img_bytes[y * stride : (y + 1) * stride]

    compressed = zlib.compress(raw, level=6)

    def chunk(tag, data):
        length = struct.pack('>I', len(data))
        crc = struct.pack('>I', zlib.crc32(tag + data) & 0xFFFFFFFF)
        return length + tag + data + crc

    ihdr = chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
    idat = chunk(b'IDAT', compressed)
    iend = chunk(b'IEND', b'')

    png = b'\x89PNG\r\n\x1a\n' + ihdr + idat + iend

    os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
    with open(filepath, 'wb') as f:
        f.write(png)

def render_charset(filepath):
    w, h = 1024, 1024
