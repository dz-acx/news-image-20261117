    def fill_rect_buf(x, y, rw, rh, color):
        x0 = max(0, x)
        y0 = max(0, y)
        x1 = min(w, x + rw)
        y1 = min(h, y + rh)
        if x1 <= x0 or y1 <= y0:
            return
        c_bytes = bytes(color)
        span_len = x1 - x0
        row_bytes = c_bytes * span_len
        for py in range(y0, y1):
            idx0 = (py * w + x0) * 3
            idx1 = idx0 + span_len * 3
            buf[idx0:idx1] = row_bytes

    def draw_text_buf(x, y, s, font, scale, color, tracking=None):
        if tracking is None:
            tracking = 1 * scale
        cx = x
        for ch in s:
            glyph = font.get(ch, font[' '])
            gw = len(glyph[0])
            gh = len(glyph)
            for r in range(gh):
                row = glyph[r]
                py = y + r * scale
                for c in range(gw):
                    if row[c] == '#':
                        px = cx + c * scale
                        if px + scale <= w and 0 <= py < h:
                            fill_rect_buf(px, py, scale, scale, color)
            cx += gw * scale + tracking

