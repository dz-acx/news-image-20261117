pixels = bytearray(bytes(COLOR_PAPER) * (WIDTH * HEIGHT))

def fill_rect(x, y, w, h, color):
    x0 = max(0, int(x))
    y0 = max(0, int(y))
    x1 = min(WIDTH, int(x + w))
    y1 = min(HEIGHT, int(y + h))
    if x1 <= x0 or y1 <= y0:
        return
    c_bytes = bytes(color)
    span_len = x1 - x0
    row_bytes = c_bytes * span_len
    for py in range(y0, y1):
        idx0 = (py * WIDTH + x0) * 3
        idx1 = idx0 + span_len * 3
        pixels[idx0:idx1] = row_bytes

def stroke_rect(x, y, w, h, thickness, color):
    t = int(thickness)
    fill_rect(x, y, w, t, color)
    fill_rect(x, y + h - t, w, t, color)
    fill_rect(x, y, t, h, color)
    fill_rect(x + w - t, y, t, h, color)

def fill_circle(cx, cy, r, color):
    cx = int(cx)
    cy = int(cy)
    r = int(r)
    if r <= 0:
        return
    r2 = r * r
    c_bytes = bytes(color)
    y_min = max(0, cy - r)
    y_max = min(HEIGHT, cy + r + 1)
    for py in range(y_min, y_max):
        dy = py - cy
        dx = int((r2 - dy * dy) ** 0.5)
        x0 = max(0, cx - dx)
        x1 = min(WIDTH, cx + dx + 1)
        if x1 > x0:
            span_len = x1 - x0
            idx0 = (py * WIDTH + x0) * 3
            pixels[idx0 : idx0 + span_len * 3] = c_bytes * span_len

def fill_polygon(pts, color):
    if len(pts) < 3:
        return
    min_y = max(0, int(min(p[1] for p in pts)))
    max_y = min(HEIGHT - 1, int(max(p[1] for p in pts)))
    c_bytes = bytes(color)
    n = len(pts)
    for py in range(min_y, max_y + 1):
        nodes = []
        for i in range(n):
            p1x, p1y = pts[i]
            p2x, p2y = pts[(i + 1) % n]
            if (p1y <= py < p2y) or (p2y <= py < p1y):
                if p1y != p2y:
                    xi = p1x + (py - p1y) * (p2x - p1x) / (p2y - p1y)
                    nodes.append(int(xi))
        nodes.sort()
        for i in range(0, len(nodes), 2):
            if i + 1 < len(nodes):
                x0 = max(0, nodes[i])
                x1 = min(WIDTH, nodes[i + 1] + 1)
                if x1 > x0:
                    span_len = x1 - x0
                    idx0 = (py * WIDTH + x0) * 3
                    pixels[idx0 : idx0 + span_len * 3] = c_bytes * span_len

def draw_line(x0, y0, x1, y1, thickness, color):
    dx = x1 - x0
    dy = y1 - y0
    dist = (dx * dx + dy * dy) ** 0.5
    t = max(1.0, float(thickness))
    if dist < 1.0:
        fill_circle(int(x0), int(y0), int(t / 2.0), color)
        return
    px = -dy / dist * (t / 2.0)
    py = dx / dist * (t / 2.0)
    pts = [
        (x0 + px, y0 + py),
        (x1 + px, y1 + py),
        (x1 - px, y1 - py),
        (x0 - px, y0 - py)
    ]
    fill_polygon(pts, color)
    fill_circle(int(x0), int(y0), int(t / 2.0), color)
    fill_circle(int(x1), int(y1), int(t / 2.0), color)

# Design coordinates helpers (1024 -> 2048)
def rect1024(x, y, w, h, color):
    fill_rect(x * 2, y * 2, w * 2, h * 2, color)

